#!/usr/bin/env python3
"""Write the decomp's data tables (decomp/src/data.c) from your own Tetris ROM.

usage: gen_data.py <tetris.nes> <data.h> <data.c>

The tables are the game's own data, so they are not kept in the repository: the build
reads them out of the ROM (`make ROM=...`). data.h says which: each table's name, its
address in the ROM (ROM_name) and its length. Nothing graphical or musical is read.

tools/gen_decomp.py writes the same file, and data.h itself, from a build of the
disassembly; use it after changing which tables there are.
"""
import hashlib, re, sys

# Tetris (USA), as examples/tetris/config.toml pins it.
ROM_SHA256 = 'ddb876c302cfd4ee19fabff8e3ede0b6801ded70c49980d1682a32d352953082'

rom_path, header, out = sys.argv[1], sys.argv[2], sys.argv[3]
rom = open(rom_path, 'rb').read()
got = hashlib.sha256(rom).hexdigest()
if got != ROM_SHA256:
    sys.exit(f'{rom_path} is not the Tetris (USA) ROM this decomp is of\n'
             f'  its sha256:  {got}\n  expected:    {ROM_SHA256}')
prg = rom[16:16 + 0x8000]

text = open(header).read()
tables = re.findall(r'/\* (.*?) \*/\n#define ROM_(\w+) 0x([0-9A-Fa-f]{4})\nextern const uint8_t (\w+)\[(\d+)\];', text)
if not tables:
    sys.exit(f'{header} names no tables')

with open(out, 'w') as c:
    c.write('/* Generated by tools/gen_decomp.py from the assembled reference disassembly. Do\n'
            ' * not edit; regenerate.\n *\n'
            ' * The tables the game logic reads, under their labels in the disassembly, and the\n'
            ' * address each had in ROM (ROM_name), for the RAM variables that point into them\n'
            ' * (demoButtonsAddr) and for reading past a table\'s end where the original does. */\n'
            '#include "data.h"\n\n')
    look = None
    for what, rom_name, addr, name, length in tables:
        assert rom_name == name, (rom_name, name)
        a, length = int(addr, 16), int(length)
        if name == 'oamContentLookup':
            look = (a, length // 2)
        c.write(f'/* {what} (${a:04X}) */\nconst uint8_t {name}[{length}] = {{')
        for i, b in enumerate(prg[a - 0x8000:a - 0x8000 + length]):
            c.write(('\n    ' if i % 16 == 0 else ' ') + f'0x{b:02X},')
        c.write('\n};\n\n')
    # How many 4-byte entries each sprite has (they end with $FF): loading one
    # into OAM staging adds 4 bytes per entry to oamStagingLength.
    a0, n = look
    c.write(f'/* the number of OAM entries (4 bytes each) of each sprite in oamContentLookup, counted to its $FF */\n'
            f'const uint8_t oamSpriteEntries[{n}] = {{')
    for i in range(n):
        a = prg[a0 - 0x8000 + 2 * i] | prg[a0 - 0x8000 + 2 * i + 1] << 8
        k = 0
        while prg[a - 0x8000 + 4 * k] != 0xFF:
            k += 1
        c.write(('\n    ' if i % 16 == 0 else ' ') + f'{k},')
    c.write('\n};\n')
print(f'{len(tables)} tables from {rom_path}', file=sys.stderr)
