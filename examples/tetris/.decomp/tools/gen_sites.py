#!/usr/bin/env python3
"""List the decomp's resume points, for loading snapshots of the original.

usage: gen_sites.py <decomp dir>

Reads src/*.c and writes src/sites.h: every PT_CALL and wait (PT_WAIT_NMI and the
WAIT_* macros) with the routine it is in (its PT_BEGIN). Each one's address is the
return address the original's JSR pushes there, which is how a snapshot's stack page
says where the original is.
"""
import glob, os, re, sys

src = os.path.join(sys.argv[1], 'src')
sites = []
for path in sorted(glob.glob(os.path.join(src, '*.c'))):
    routine = None
    for line in open(path):
        m = re.search(r'PT_BEGIN\((PT_\w+)\)', line)
        if m:
            routine = m.group(1)
        m = re.search(r'\b(PT_CALL|PT_WAIT_NMI|WAIT_RESET_OAM|WAIT_DISABLE_RENDERING|WAIT_ENABLE_RENDERING)\((0x[0-9A-Fa-f]{4})', line)
        if m and not line.lstrip().startswith(('#', '*', '/*')):
            kind = 'SITE_CALL' if m.group(1) == 'PT_CALL' else 'SITE_WAIT'
            sites.append((int(m.group(2), 16), routine, kind, os.path.basename(path)))

with open(os.path.join(src, 'sites.h'), 'w') as f:
    f.write('/* Generated by tools/gen_sites.py from the sources in src. Do not edit; regenerate.\n'
            ' * Every place a resumable routine can stop: the address the original\'s JSR\n'
            ' * pushes there, the routine, and whether it calls a routine or waits for the NMI. */\n'
            '#ifndef TETRIS_SITES_H\n#define TETRIS_SITES_H\n\n'
            'enum { SITE_CALL, SITE_WAIT };\n\n'
            'static const struct pt_site {\n    uint16_t ret;\n    uint8_t routine;\n    uint8_t kind;\n} pt_sites[] = {\n')
    for ret, routine, kind, fn in sorted(sites):
        f.write(f'    {{0x{ret:04X}, {routine}, {kind}}}, /* {fn} */\n')
    f.write('};\n\n#endif\n')
print(f'{len(sites)} sites', file=sys.stderr)
