#!/usr/bin/env python3
"""Generate the decomp's RAM layout and game tables from a TetrisNESDisasm build.

usage: gen_decomp.py <disasm dir> <decomp dir>

Writes:
  include/tetris/ram.h  struct tetris_vars: every RAM variable of the original, named as
                        in the disassembly, at its original offset (checked with
                        static asserts), and union tetris_ram over it.
  src/ram_names.h       the names the game code uses: A_name (the address) and name
                        (the variable in the current game, T->ram.v.name).
  src/data.h, data.c    the tables the game logic reads, transcribed from the assembled
                        disassembly (tetris.nes) under their labels. Nothing graphical
                        or musical is included.
"""
import os, re, sys

disasm, out = sys.argv[1], sys.argv[2]

# ---- RAM ------------------------------------------------------------------

sizes = {}
for line in open(os.path.join(disasm, 'tetris-ram.asm')):
    m = re.match(r'^\s*([A-Za-z_]\w*):\s*\.res\s+(\$?[0-9A-Fa-f]+)', line)
    if m:
        n = m.group(2)
        sizes[m.group(1)] = int(n[1:], 16) if n.startswith('$') else int(n)

ram = {}
skip = False
for line in open(os.path.join(disasm, 'main.asm'), encoding='latin-1'):
    s = line.split(';')[0].rstrip()
    if s.startswith('.if NWC = 1'):
        skip = True; continue
    if s.startswith('.else') and skip:
        skip = False; continue
    if s.startswith('.endif'):
        skip = False; continue
    if skip:
        continue
    m = re.match(r'^([A-Za-z_]\w*)\s*:=\s*\$([0-9A-Fa-f]{4})\s*$', s)
    if m:
        addr = int(m.group(2), 16)
        if addr < 0x800:
            ram.setdefault(m.group(1), addr)
    if s.startswith('.segment'):
        break

# Variables the code indexes past their declared size (pointers, arrays declared
# as one byte), extended over the unnamed bytes that follow them.
SIZE_OVERRIDES = {'demoButtonsAddr': 2, 'ending_customVars': 7, 'stack': 256}
items = sorted(((a, n, SIZE_OVERRIDES.get(n, sizes.get(n, 1))) for n, a in ram.items()))

with open(os.path.join(out, 'include/tetris/ram.h'), 'w') as f:
    f.write('''/* Generated by tools/gen_decomp.py from the reference disassembly (main.asm and
 * tetris-ram.asm). Do not edit; regenerate.
 *
 * The game's 2 KB of RAM, with every variable at the offset the NES gives it, so
 * that `b[addr]` and the named field are the same byte. Gaps are bytes the
 * disassembly does not name. */
#ifndef TETRIS_RAM_H
#define TETRIS_RAM_H

#include <stddef.h>
#include <stdint.h>

struct tetris_vars {
''')
    pos = 0
    for a, n, s in items:
        if a > pos:
            f.write(f'    uint8_t _gap_{pos:04X}[{a - pos}];\n')
        f.write(f'    uint8_t {n}{"[%d]" % s if s > 1 else ""}; /* ${a:04X} */\n')
        pos = a + s
    if pos < 0x800:
        f.write(f'    uint8_t _gap_{pos:04X}[{0x800 - pos}];\n')
    f.write('};\n\nunion tetris_ram {\n    uint8_t b[0x800];\n    struct tetris_vars v;\n};\n\n')
    f.write('_Static_assert(sizeof(struct tetris_vars) == 0x800, "RAM is 2 KB");\n')
    for a, n, s in items:
        f.write(f'_Static_assert(offsetof(struct tetris_vars, {n}) == 0x{a:04X}, "{n}");\n')
    f.write('\n#endif\n')

with open(os.path.join(out, 'src/ram_names.h'), 'w') as f:
    f.write('''/* Generated by tools/gen_decomp.py. Do not edit; regenerate.
 *
 * The names the game code uses for RAM, as in the disassembly: A_name is the
 * variable's address, name the variable itself in the game being run (T). */
#ifndef TETRIS_RAM_NAMES_H
#define TETRIS_RAM_NAMES_H

''')
    for a, n, s in items:
        f.write(f'#define A_{n} 0x{a:04X}\n#define {n} (T->ram.v.{n})\n')
    f.write('\n#endif\n')

# ---- Tables -----------------------------------------------------------------

segs, labels = {}, {}
for line in open(os.path.join(disasm, 'tetris.dbg')):
    kind, _, rest = line.rstrip('\n').partition('\t')
    f_ = dict(re.findall(r'(\w+)=("[^"]*"|[^,]+)', rest))
    if kind == 'seg' and 'ooffs' in f_ and f_['name'].strip('"') not in ('HEADER', 'CHR'):
        segs[f_['id']] = True
    elif kind == 'sym' and f_.get('type') == 'lab' and f_.get('seg') in segs:
        name = f_['name'].strip('"')
        if not name.startswith('@'):
            labels.setdefault(name, int(f_['val'], 16))
addrs = sorted(set(labels.values()))
prg = open(os.path.join(disasm, 'tetris.nes'), 'rb').read()[16:16 + 0x8000]

# name, what it is (for the comment), and the length when it isn't "up to the next label"
TABLES = [
    ('rotationTable', 'the orientation after rotating: two per orientation (B, then A)', None),
    ('orientationTable', 'four squares per orientation: row offset, tile, column offset', 0x100),
    ('framesPerDropTable', 'frames per row of fall, by level 0-28', None),
    ('multBy10Table', 'row * 10, the playfield offset of each row', None),
    ('rngTable', 'B-type garbage squares: four tiles and four empties', None),
    ('spawnTable', 'the spawn orientation of each of the 7 pieces', 7),
    ('spawnOrientationFromOrientation', 'any orientation to its piece\'s spawn orientation', None),
    ('tetriminoTypeFromOrientation', 'orientation to piece type (0-6)', None),
    ('pointsTable', 'points for 0-4 lines, BCD, low byte first', None),
    ('garbageLines', 'garbage sent for 0-4 lines (two-player)', None),
    ('typeBBlankInitCountByHeightTable', 'B-type: last playfield square cleared, by height', None),
    ('typebSuccessGraphic', 'B-type success message, written into the playfield; ends with $80', None),
    ('levelDisplayTable', 'level number as BCD, levels 0-29', None),
    ('defaultHighScoresTable', 'the high score table on a cold boot: names, scores, levels; ends with $FF', None),
    ('highScoreIndexToHighScoreNamesOffset', 'high score entry to its name\'s offset', None),
    ('highScoreIndexToHighScoreScoresOffset', 'high score entry to its score\'s offset', None),
    ('LAA2A', 'A-type ending: the rocket\'s starting y, by ending', None),
    ('demoButtonsTable', 'the demo\'s input: pairs of (buttons, frames to hold them)', None),
    ('demoTetriminoTypeTable', 'the demo\'s pieces: bits 4-6 of each byte pick from spawnTable', 0x100),
    ('orientationToSpriteTable', 'the next piece preview\'s sprite, by orientation', None),
    ('oamContentLookup', 'the sprites\' ROM addresses, low byte first: the scratch values loading one leaves', None),
]

with open(os.path.join(out, 'src/data.h'), 'w') as h, open(os.path.join(out, 'src/data.c'), 'w') as c:
    head = ('/* Generated by tools/gen_decomp.py from the assembled reference disassembly. Do\n'
            ' * not edit; regenerate.\n *\n'
            ' * The tables the game logic reads, under their labels in the disassembly, and the\n'
            ' * address each had in ROM (ROM_name), for the RAM variables that point into them\n'
            ' * (demoButtonsAddr) and for reading past a table\'s end where the original does. */\n')
    h.write(head + '#ifndef TETRIS_DATA_H\n#define TETRIS_DATA_H\n\n#include <stdint.h>\n\n')
    c.write(head + '#include "data.h"\n\n')
    for name, what, length in TABLES:
        a = labels[name]
        if length is None:
            length = next(x for x in addrs if x > a) - a
        data = prg[a - 0x8000:a - 0x8000 + length]
        h.write(f'/* {what} */\n#define ROM_{name} 0x{a:04X}\nextern const uint8_t {name}[{length}];\n\n')
        c.write(f'/* {what} (${a:04X}) */\nconst uint8_t {name}[{length}] = {{')
        for i, b in enumerate(data):
            c.write(('\n    ' if i % 16 == 0 else ' ') + f'0x{b:02X},')
        c.write('\n};\n\n')
    # How many 4-byte entries each sprite has (they end with $FF): loading one
    # into OAM staging adds 4 bytes per entry to oamStagingLength.
    look = labels['oamContentLookup']
    n = (next(x for x in addrs if x > look) - look) // 2
    counts = []
    for i in range(n):
        a = prg[look - 0x8000 + 2 * i] | prg[look - 0x8000 + 2 * i + 1] << 8
        k = 0
        while prg[a - 0x8000 + 4 * k] != 0xFF:
            k += 1
        counts.append(k)
    h.write(f'/* the number of OAM entries (4 bytes each) of each sprite in oamContentLookup */\n'
            f'extern const uint8_t oamSpriteEntries[{n}];\n\n')
    c.write(f'/* the number of OAM entries (4 bytes each) of each sprite in oamContentLookup, counted to its $FF */\n'
            f'const uint8_t oamSpriteEntries[{n}] = {{')
    for i, k in enumerate(counts):
        c.write(('\n    ' if i % 16 == 0 else ' ') + f'{k},')
    c.write('\n};\n')
    h.write('#endif\n')
print(f'{len(items)} RAM names, {len(TABLES)} tables', file=sys.stderr)
