#!/usr/bin/env python3
"""Generate the port's RAM map and ROM label headers from a TetrisNESDisasm build.

usage: gen_headers.py <disasm dir> <out dir>

Writes:
  ram_map.h    every RAM variable from main.asm's `name := $addr` list, as an address
               constant (A_name) and an lvalue (name) or, for multi-byte variables, a
               pointer into tetris_ram. Sizes come from tetris-ram.asm.
  rom_labels.h every label ld65 placed in PRG, as an address constant (ROM_name).

Only names and addresses are written, never ROM bytes.
"""
import os, re, sys

disasm, out = sys.argv[1], sys.argv[2]

# Sizes from tetris-ram.asm: "name: .res N ; $addr"
sizes = {}
for line in open(os.path.join(disasm, 'tetris-ram.asm')):
    m = re.match(r'^\s*([A-Za-z_]\w*):\s*\.res\s+(\$?[0-9A-Fa-f]+)', line)
    if m:
        n = m.group(2)
        sizes[m.group(1)] = int(n[1:], 16) if n.startswith('$') else int(n)

# Addresses from main.asm (the non-NWC branch of its .if NWC block)
ram = {}
skip = False
for line in open(os.path.join(disasm, 'main.asm'), encoding='latin-1'):
    s = line.split(';')[0].rstrip()
    if s.startswith('.if NWC = 1'):
        skip = True; continue
    if s.startswith('.else') and skip:
        skip = False; continue
    if s.startswith('.endif'):
        skip = False; continue
    if skip:
        continue
    m = re.match(r'^([A-Za-z_]\w*)\s*:=\s*\$([0-9A-Fa-f]{4})\s*$', s)
    if m:
        addr = int(m.group(2), 16)
        if addr < 0x800:
            ram.setdefault(m.group(1), addr)
    if s.startswith('.segment'):
        break

with open(os.path.join(out, 'ram_map.h'), 'w') as f:
    f.write('/* Generated by tools/gen_headers.py from the reference disassembly\n'
            ' * (main.asm and tetris-ram.asm). Every variable of the original game, at its\n'
            ' * original address in the 2 KB of RAM. Do not edit; regenerate. */\n'
            '#ifndef TETRIS_RAM_MAP_H\n#define TETRIS_RAM_MAP_H\n\n')
    for name, addr in sorted(ram.items(), key=lambda kv: (kv[1], kv[0])):
        size = sizes.get(name, 1)
        f.write(f'#define A_{name} 0x{addr:04X}\n')
        if size > 1:
            f.write(f'#define {name} (tetris_ram + A_{name}) /* {size} bytes */\n')
        else:
            f.write(f'#define {name} (tetris_ram[A_{name}])\n')
    f.write('\n#endif\n')

# ROM labels from the .dbg
segs, labels = {}, {}
for line in open(os.path.join(disasm, 'tetris.dbg')):
    kind, _, rest = line.rstrip('\n').partition('\t')
    f_ = dict(re.findall(r'(\w+)=("[^"]*"|[^,]+)', rest))
    if kind == 'seg' and 'ooffs' in f_ and f_['name'].strip('"') not in ('HEADER', 'CHR'):
        segs[f_['id']] = True
    elif kind == 'sym' and f_.get('type') == 'lab' and f_.get('seg') in segs:
        name = f_['name'].strip('"')
        if not name.startswith('@'):
            labels.setdefault(name, int(f_['val'], 16))
with open(os.path.join(out, 'rom_labels.h'), 'w') as f:
    f.write('/* Generated by tools/gen_headers.py from the reference build\'s tetris.dbg.\n'
            ' * CPU addresses of every label in PRG ROM (code and data). Only names and\n'
            ' * addresses: the data itself is read from the player\'s ROM. Do not edit. */\n'
            '#ifndef TETRIS_ROM_LABELS_H\n#define TETRIS_ROM_LABELS_H\n\n')
    for name, addr in sorted(labels.items(), key=lambda kv: (kv[1], kv[0])):
        f.write(f'#define ROM_{name} 0x{addr:04X}\n')
    f.write('\n#endif\n')
print(f'{len(ram)} RAM names, {len(labels)} ROM labels', file=sys.stderr)
